<?php
session_start();

require_once __DIR__ . '/../bootstrap.php';

header('Content-Type: application/json');

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['success' => false, 'error' => 'Method Not Allowed']);
    exit;
}

if (!isset($_SESSION['user_id'])) {
    http_response_code(401);
    echo json_encode(['success' => false, 'error' => 'Unauthorized']);
    exit;
}

$input = $_POST;
$provider = trim($input['provider'] ?? '');
$baseUrl  = trim($input['baseUrl'] ?? '');
$apiKey   = trim($input['apiKey'] ?? '');
$model    = trim($input['model'] ?? '');

$allowedProviders = ['gemini', 'lmstudio', 'ollama', 'openai', 'openai-oauth', 'minimax'];
if (!in_array($provider, $allowedProviders, true)) {
    http_response_code(400);
    echo json_encode(['success' => false, 'error' => 'Invalid provider']);
    exit;
}

$configFile = __DIR__ . '/../config.php';
$config = require $configFile;

$config['LLM_PROVIDER'] = $provider;
$config['LLM_BASE_URL'] = $baseUrl;
$config['LLM_MODEL']    = $model;
if ($apiKey !== '') {
    $config['LLM_API_KEY'] = $apiKey;
}

$newContent = "<?php\n/**\n * JobPulse Configuration\n * GENERATED BY settings UI — manual edits preserved.\n */\nreturn " . var_export($config, true) . ";\n";

if (file_put_contents($configFile, $newContent) === false) {
    http_response_code(500);
    echo json_encode(['success' => false, 'error' => 'Failed to write config.php']);
    exit;
}

echo json_encode(['success' => true, 'message' => 'Settings saved']);
